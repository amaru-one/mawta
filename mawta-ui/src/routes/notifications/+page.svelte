<script lang="ts">
	import { Action, EmptyState, Icon, Segmented } from '$lib/design-system';
	import { onMount } from 'svelte';
	import TopBar from '$lib/components/TopBar.svelte';
	import type { IconName } from '$lib/icons';
	import { hapticTap } from '$lib/haptics';
	import {
		loadNotifications,
		markNotificationsRead,
		markNotificationRead,
	} from '$lib/notifications';
	import { notifications, unreadNotificationCount } from '$lib/stores';
	import type { AppNotification, AppNotificationType } from '$lib/types';

	type Filter = 'all' | 'alerts' | 'reminders';

	let filter = $state<Filter>('all');

	const FILTERS: Array<{ id: Filter; label: string }> = [
		{ id: 'all', label: 'Todas' },
		{ id: 'alerts', label: 'Alertas' },
		{ id: 'reminders', label: 'Recordatorios' },
	];

	const ICON: Record<AppNotificationType, IconName> = {
		risk: 'trending-down',
		tip: 'sparkles',
		reminder: 'clipboard-check',
	};

	// Alerts are the assistant's output; reminders are plain app to-dos.
	const alerts = $derived($notifications.filter((n) => n.aiGenerated));
	const reminders = $derived($notifications.filter((n) => !n.aiGenerated));
	// "Marcar" acts on what the teacher can see under the current filter, not on everything.
	const visibleUnreadIds = $derived(
		[...(filter !== 'reminders' ? alerts : []), ...(filter !== 'alerts' ? reminders : [])]
			.filter((n) => !n.read)
			.map((n) => n.id)
	);

	const showAlerts = $derived(filter !== 'reminders' && alerts.length > 0);
	const showReminders = $derived(filter !== 'alerts' && reminders.length > 0);

	// The layout loads the feed once after sign-in for the badge; this page
	// refreshes it on every visit so the list is always current.
	onMount(() => {
		void loadNotifications().catch(() => {});
	});

	const relativeTime = (date: Date): string => {
		const minutes = Math.round((Date.now() - date.getTime()) / 60000);
		if (minutes < 1) return 'Ahora';
		if (minutes < 60) return `Hace ${minutes} min`;
		const hours = Math.round(minutes / 60);
		if (hours < 24) return `Hace ${hours} ${hours === 1 ? 'hora' : 'horas'}`;
		const days = Math.round(hours / 24);
		return `Hace ${days} ${days === 1 ? 'día' : 'días'}`;
	};

	function open(n: AppNotification): void {
		hapticTap();
		if (!n.read) markNotificationRead(n.id);
	}

	// Built here rather than inline: Svelte collapses the whitespace that would
	// otherwise sit between a {#if} block and the text beside it.
	// Reminders name their course in the message itself, so the metadata line
	// carries `detail` instead and doesn't repeat it.
	const metaLine = (n: AppNotification): string =>
		[n.detail ?? n.courseName, n.read ? 'Leído' : null, relativeTime(n.createdAt)]
			.filter(Boolean)
			.join(' · ');
</script>

<svelte:head>
	<title>Notificaciones</title>
</svelte:head>
<div class="view">
	<TopBar back="/" showBell={false} />

	<div class="body">
		<div class="row head">
			<p class="title">Notificaciones</p>
			{#if $unreadNotificationCount > 0}
				<Action variant="link" onclick={() => void markNotificationsRead(visibleUnreadIds)}
					>{filter === 'all' ? 'Marcar todas leídas' : 'Marcar estas como leídas'}</Action
				>
			{/if}
		</div>

		<div class="filters">
			<Segmented
				label="Filtrar notificaciones"
				options={FILTERS.map((f) => ({ value: f.id, label: f.label }))}
				value={filter}
				onchange={(value) => (filter = value as typeof filter)}
			/>
		</div>

		{#if showAlerts}
			<p class="eyebrow">ALERTAS · TENDENCIAS DETECTADAS</p>
			<div class="stack">
				{#each alerts as n (n.id)}
					<button class="card item pressable" class:read={n.read} onclick={() => open(n)}>
						<!-- Accent icon = generated by the assistant. -->
						<span class="badge ai"><Icon name={n.icon ?? ICON[n.type]} size={16} /></span>
						<span class="content">
							<span class="message">
								{#if n.studentName}<strong>{n.studentName}</strong>{' '}{/if}{n.message}
							</span>
							<span class="meta">{metaLine(n)}</span>
						</span>
						{#if !n.read}<span class="unread ai-dot"><span class="mw-sr-only">Sin leer.</span></span
							>{/if}
					</button>
				{/each}
			</div>
		{/if}

		{#if showReminders}
			<p class="eyebrow">RECORDATORIOS · PENDIENTES</p>
			<div class="stack">
				{#each reminders as n (n.id)}
					<button class="card item pressable" class:read={n.read} onclick={() => open(n)}>
						<span class="badge"><Icon name={n.icon ?? ICON[n.type]} size={16} /></span>
						<span class="content">
							<span class="message">
								{n.message}{#if n.courseName}{' — '}<strong>{n.courseName}</strong>{/if}
							</span>
							<span class="meta">{metaLine(n)}</span>
						</span>
						{#if !n.read}<span class="unread"><span class="mw-sr-only">Sin leer.</span></span>{/if}
					</button>
				{/each}
			</div>
		{/if}

		{#if !showAlerts && !showReminders}
			<EmptyState
				title="No hay notificaciones"
				description="Aquí aparecerán tus alertas y recordatorios."
			/>
		{/if}
	</div>
</div>

